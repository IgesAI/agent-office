import test from 'node:test';
import assert from 'node:assert/strict';
import { installHeadquarters } from '../src/client/features/headquarters';
import { store } from '../src/client/state';
import { Messages } from '../src/client/core/registry';
import type { Ctx } from '../src/client/core/context';
import type { ServerMsg, WorkerInfo } from '../src/shared/protocol';

test('workstation clears stale terminal data until reconnect reconciliation and clears a removed worker', () => {
  const text: string[] = [];
  const g = { save() {}, restore() {}, translate() {}, fillRect() {}, fillText(s: string) { text.push(s); } };
  const net = { up: false, onStatus(fn: () => void) { this.changed = fn; }, changed() {} };
  const messages = new Messages<ServerMsg>(() => {});
  const canvas = { width: 1024, height: 408, getContext: () => g };
  const ctx = { net, messages, office: { studioScreens: [{ deskId: 'desk-1', canvas, texture: {} }] } } as unknown as Ctx;
  store.workers.set('worker', { id: 'worker', deskId: 'desk-1', name: 'Real worker', status: 'working' } as WorkerInfo);
  store.screens.set('worker', { cols: 8, rows: 1, cursor: [0, 0], version: 1, lines: [[['RECEIVED', -1, -1, 0]]] });
  installHeadquarters(ctx);
  assert.deepEqual(text, ['Waiting for office connection']);
  text.length = 0;
  net.up = true;
  net.changed();
  store.emit('screens');
  assert.equal(text.includes('RECEIVED'), false, 'an open transport alone must not expose cached output');
  messages.dispatch({ t: 'welcome' } as ServerMsg);
  assert.ok(text.includes('RECEIVED'));
  assert.ok(text.includes('Real worker · working'));
  text.length = 0;
  net.up = false;
  net.changed();
  assert.deepEqual(text, ['Waiting for office connection']);
  text.length = 0;
  net.up = true;
  net.changed();
  assert.equal(text.includes('RECEIVED'), false);
  messages.dispatch({ t: 'welcome' } as ServerMsg);
  assert.ok(text.includes('RECEIVED'));
  text.length = 0;
  store.workers.clear();
  store.screens.clear();
  store.emit('workers');
  assert.deepEqual(text, ['Available workstation']);
});
